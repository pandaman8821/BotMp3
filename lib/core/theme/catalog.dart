/// Devuelve el tema por id; si no existe, el tema por defecto (glass).
BotTokens themeById(String? id) {
  for (final BotTokens t in kThemes) {
    if (t.id == id) return t;
  }
  return kThemes.firstWhere((BotTokens t) => t.id == 'glass', orElse: () => kThemes.first);
}

